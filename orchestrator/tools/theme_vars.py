#!/usr/bin/env python3
"""
Theme-variable conversion for the stage module stylesheets.

1. Inside each module file's `var CSS = [ ... ].join` block, every literal colour #rrggbb / #rgb
   becomes var(--x-rrggbb,#rrggbb): the dark (DH) render is unchanged (the fallback is the
   original colour) while another profile can override the variable.
2. Writes lib/stage/theme-lc.js: an explicit mapping dark hex -> light-profile colour (refs R3/R4,
   SPEC.md 2.2), classified by role (surface / divider / border / line / ink / accent / tint).
   The mapping is generated once, then reviewed and hand-tuned in that file.

Idempotent: already-wrapped colours are left alone.
"""
import re, colorsys, pathlib, json

STAGE = pathlib.Path(__file__).resolve().parents[2] / "video-engine/compositions/components/lib/stage"
FILES = ["modules-dh.js", "modules-dh2.js", "modules-dh3.js", "modules-dh4.js"]
HEX = re.compile(r"(?<![\w-])#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b")

# LC palette (SPEC 2.2, R4 canonical)
LC = {
    "bg": "#f4f4ed", "surface": "#fefcf8", "surface2": "#f1f2ec", "chrome": "#e6ede9",
    "divider": "#e5e3df", "border": "#c6cbc7", "line": "#b9bebd",
    "ink": "#17232b", "ink2": "#474c4d", "muted": "#626667", "dim": "#c9ccc6",
}
# hue buckets -> (accent, tint fill, tint line) from R4 (+ R3 red for danger)
HUES = {
    "red": ("#b23a3f", "#fae4da", "#e3b1a0"), "orange": ("#b14b30", "#fae4da", "#e3b1a0"),
    "amber": ("#855412", "#f7f1e7", "#dcc7a0"), "green": ("#187a5b", "#ddf2e7", "#a9d3bc"),
    "cyan": ("#1f6f8b", "#e0eef3", "#a8cbd8"), "blue": ("#1766da", "#e5eef9", "#b9cdeb"),
    "purple": ("#6d4ea5", "#eae6f2", "#c6b9dd"), "pink": ("#a33a63", "#f6e3ea", "#ddb3c3"),
}


def norm(h):
    h = h.lower().lstrip("#")
    return h if len(h) == 6 else "".join(c * 2 for c in h)


def hue_bucket(r, g, b):
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    d = h * 360
    if d < 15 or d >= 340: return "red"
    if d < 35: return "orange"
    if d < 60: return "amber"
    if d < 160: return "green"
    if d < 200: return "cyan"
    if d < 250: return "blue"
    if d < 290: return "purple"
    return "pink"


def classify(hx):
    r, g, b = (int(hx[i:i + 2], 16) / 255 for i in (0, 2, 4))
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    mx, mn = max(r, g, b), min(r, g, b)
    sat = (mx - mn)
    if sat < 0.09:  # neutrals by lightness
        if l < 0.035: return LC["surface"]
        if l < 0.075: return LC["surface2"]
        if l < 0.10: return LC["divider"]
        if l < 0.20: return LC["border"]
        if l < 0.32: return LC["line"]
        if l < 0.50: return LC["muted"]
        if l < 0.72: return LC["ink2"]
        return LC["ink"]
    bucket = hue_bucket(r, g, b)
    acc, fill, line = HUES[bucket]
    if l < 0.16: return fill  # dark tint fill
    if l < 0.30: return line  # tint border
    return acc  # accent / text in role colour


def main():
    seen = set()
    for f in FILES:
        p = STAGE / f
        s = p.read_text(encoding="utf-8")
        a = s.index("var CSS = [")
        b = s.index("].join", a)
        block = s[a:b]

        def rep(m):
            start = m.start()
            if block[max(0, start - 1)] == "," and block[max(0, start - 9):start].endswith("--x-" + norm(m.group(1)) + ","):
                return m.group(0)
            hx = norm(m.group(1))
            seen.add(hx)
            return f"var(--x-{hx},#{hx})"

        # skip colours already inside var(--x-...,#...)
        parts = re.split(r"(var\(--x-[0-9a-f]{6},#[0-9a-f]{6}\))", block)
        out = []
        for part in parts:
            if part.startswith("var(--x-"):
                seen.add(part[8:14])
                out.append(part)
            else:
                out.append(HEX.sub(lambda m: (seen.add(norm(m.group(1))) or f"var(--x-{norm(m.group(1))},#{norm(m.group(1))})"), part))
        s = s[:a] + "".join(out) + s[b:]
        p.write_text(s, encoding="utf-8")
    mapping = {hx: classify(hx) for hx in sorted(seen)}
    js = ["/* generated by orchestrator/tools/theme_vars.py, then hand-tuned: DH colour -> LC (light, refs R3/R4) */",
          "(function (global) {", '  "use strict";', "  var HF = (global.HFStage = global.HFStage || { modules: {} });",
          "  HF.themes = HF.themes || {};", "  HF.themes.LC = {"]
    js += [f'    "{k}": "{v}",' for k, v in mapping.items()]
    js += ["  };", "})(typeof window !== \"undefined\" ? window : globalThis);", ""]
    out = STAGE / "theme-lc.js"
    if out.exists():
        print("theme-lc.js exists; new keys only:", sorted(set(mapping) - set(re.findall(r'"([0-9a-f]{6})":', out.read_text()))))
    else:
        out.write_text("\n".join(js), encoding="utf-8")
        print("wrote", out, len(mapping), "colours")


if __name__ == "__main__":
    main()
