"""
Synthetic, clearly-fake test "tracks" for the music library pipeline (music_index.py, musicPlan.js,
sfx_mix.py --music-plan). numpy only, deterministic. NOT music for videos: square-ish tones, a click
kick and noise hats, so nobody mistakes them for real library tracks.

  python make_test_music.py <out_dir>        # writes <out_dir>/<mood>/*.wav + .license.json sidecars

Each track: 44.1 kHz stereo (so the mixer's resampling is exercised), 2-bar quiet intro, then 4-bar
phrases with an accented downbeat, a 2 s fade-out; tempos/keys/energy differ per track.
"""
import json
import math
import sys
import wave
from pathlib import Path

import numpy as np

SR = 44100

TRACKS = [
    # mood, name, bpm, root midi, minor, bars, energy (0..1), low (kick/bass weight)
    ("tension", "synthetic-tension-a", 100, 45, True, 16, 0.75, 0.8),
    ("tension", "synthetic-tension-b", 88, 43, True, 14, 0.6, 0.6),
    ("investigative", "synthetic-investigative-a", 92, 50, True, 12, 0.5, 0.5),
    ("hopeful", "synthetic-hopeful-a", 76, 48, False, 10, 0.4, 0.35),
    ("calm", "synthetic-calm-a", 70, 53, False, 10, 0.2, 0.2),
    ("trailer", "synthetic-trailer-a", 118, 38, True, 16, 0.95, 1.0),
]


def mtof(m):
    return 440.0 * 2 ** ((m - 69) / 12)


def tone(f, n, bright):
    t = np.arange(n) / SR
    y = np.sin(2 * math.pi * f * t)
    for h in (3, 5):
        y += bright / h * np.sin(2 * math.pi * f * h * t)
    return y


def env(n, a, r):
    e = np.ones(n)
    na, nr = max(1, int(a * SR)), max(1, int(r * SR))
    e[:na] = np.linspace(0, 1, na)
    e[-nr:] *= np.linspace(1, 0, nr)
    return e


def kick(n):
    t = np.arange(n) / SR
    f = 45 + 110 * np.exp(-t / 0.03)
    return np.sin(2 * math.pi * np.cumsum(f) / SR) * np.exp(-t / 0.12)


def render(bpm, root, minor, bars, energy, low, seed):
    r = np.random.default_rng(seed)
    beat = 60.0 / bpm
    intro_bars = 2
    total_bars = bars
    n = int((total_bars * 4 * beat + 2.0) * SR)
    y = np.zeros(n)
    third = 3 if minor else 4
    prog = [0, 8 if minor else 9, 3 if minor else 5, 7]  # i-VI-III-v / I-vi-IV-V (roughly)
    for b in range(total_bars):
        t0 = b * 4 * beat
        i0 = int(t0 * SR)
        nb = int(4 * beat * SR)
        deg = prog[b % 4]
        chord = [root + 12 + deg, root + 12 + deg + third, root + 12 + deg + 7]
        lvl = 0.25 if b < intro_bars else 1.0
        pad = sum(tone(mtof(m), nb, 0.3 * energy) for m in chord) / 3 * env(nb, 0.05, 0.2)
        y[i0:i0 + nb] += 0.18 * lvl * pad
        if b >= intro_bars:
            bass = tone(mtof(root + deg - 12 if deg < 7 else root + deg - 24), nb, 0.2) * env(nb, 0.01, 0.1)
            y[i0:i0 + nb] += 0.22 * low * bass
            for k in range(4):
                ik = int((t0 + k * beat) * SR)
                nk = int(0.35 * SR)
                acc = 1.0 if k == 0 else 0.55
                if k % 2 == 0 or energy > 0.55:
                    seg = y[ik:ik + nk]
                    seg += 0.5 * low * acc * kick(nk)[: len(seg)]
                ih = int((t0 + (k + 0.5) * beat) * SR)
                nh = int(0.04 * SR)
                seg = y[ih:ih + nh]
                seg += 0.08 * energy * r.standard_normal(nh)[: len(seg)] * np.exp(-np.arange(len(seg)) / (0.008 * SR))
    y *= env(n, 0.01, 2.0)
    y /= np.max(np.abs(y)) or 1
    y *= 10 ** (-3 / 20)
    return np.stack([y, np.roll(y, 40) * 0.95], axis=1)


def write(p, x):
    p.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(p), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((np.clip(x, -1, 1) * 32767).astype("<i2").tobytes())


def main():
    out = Path(sys.argv[1])
    for i, (mood, name, bpm, root, minor, bars, energy, low) in enumerate(TRACKS):
        p = out / mood / f"{name}.wav"
        write(p, render(bpm, root, minor, bars, energy, low, 11 + i))
        side = {
            "title": name.replace("-", " ").title(),
            "artist": "HFPipeline test synth",
            "source": "synthetic",
            "url": "",
            "license": "test-only (generated by make_test_music.py)",
            "credit": f"Music: {name} (synthetic test tone, not for release)",
        }
        (out / mood / f"{name}.wav.license.json").write_text(json.dumps(side, indent=1), encoding="utf-8")
    # one SFX: a sub-drop, credited through a folder-level LICENSES.md table instead of a sidecar
    n = int(1.2 * SR)
    t = np.arange(n) / SR
    s = np.sin(2 * math.pi * np.cumsum(60 * np.exp(-t / 0.6) + 25) / SR) * np.exp(-t / 0.5)
    write(out / "sfx" / "synthetic-sub-drop.wav", np.stack([s, s], axis=1) * 0.7)
    (out / "sfx" / "LICENSES.md").write_text(
        "| file | title | artist | source | url | license | credit |\n|---|---|---|---|---|---|---|\n"
        "| synthetic-sub-drop.wav | Sub drop | HFPipeline test synth | synthetic | | test-only | |\n",
        encoding="utf-8",
    )
    print(json.dumps({"dir": str(out), "tracks": len(TRACKS), "sfx": 1}))


if __name__ == "__main__":
    main()
