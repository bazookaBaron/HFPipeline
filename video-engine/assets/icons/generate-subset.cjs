"use strict";

// Bulk mechanical extraction from an official, pinned lucide-static package.
// Usage: node generate-subset.cjs <extracted npm package directory>
const fs = require("node:fs");
const path = require("node:path");

const source = path.resolve(process.argv[2] || "");
const output = __dirname;
const helper = path.resolve(__dirname, "..", "..", "compositions", "components", "lib", "icons.js");
const pkg = JSON.parse(fs.readFileSync(path.join(source, "package.json"), "utf8"));
if (pkg.name !== "lucide-static" || pkg.version !== "1.48.0" || pkg.license !== "ISC") {
  throw new Error("Expected official lucide-static@1.48.0 with ISC license");
}
const names = [
  "server", "database", "app-window", "laptop", "smartphone", "router", "cloud",
  "lock", "shield", "key", "file", "folder", "git-branch", "terminal", "users",
  "user", "rows-3", "database-zap", "globe", "cpu", "triangle-alert",
  "circle-check", "x", "clock", "zap", "package", "network", "monitor",
  "upload", "download",
];
const svgByName = {};
const manifest = {
  source: "https://www.npmjs.com/package/lucide-static",
  package: "lucide-static", version: pkg.version, license: "ISC (and MIT for Feather-derived icons)",
  licenseFile: "LICENSE", icons: {},
};
for (const name of names) {
  const modulePath = path.join(source, "dist", "esm", "icons", `${name}.mjs`);
  const moduleText = fs.readFileSync(modulePath, "utf8");
  const match = moduleText.match(/const\s+\w+\s*=\s*`([\s\S]*?)`;/);
  if (!match || !/^\s*<svg\b/.test(match[1]) || !/<\/svg>\s*$/.test(match[1])) {
    throw new Error(`Unexpected SVG module format: ${name}`);
  }
  const svg = `${match[1].trim()}\n`;
  svgByName[name] = svg;
  fs.writeFileSync(path.join(output, `${name}.svg`), svg);
  manifest.icons[name] = { file: `${name}.svg`, source: `dist/esm/icons/${name}.mjs`,
    version: pkg.version, license: manifest.license };
}
fs.copyFileSync(path.join(source, "LICENSE"), path.join(output, "LICENSE"));
fs.writeFileSync(path.join(output, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);

const helperText = `"use strict";\n// Generated by assets/icons/generate-subset.cjs from lucide-static@1.48.0.\n// See assets/icons/LICENSE for the ISC and Feather-derived MIT notices.\n(function (global) {\n  const SVG = ${JSON.stringify(svgByName, null, 2)};\n  function create(name, options = {}) {\n    if (!Object.prototype.hasOwnProperty.call(SVG, name)) throw new Error("Unknown icon: " + name);\n    const doc = new DOMParser().parseFromString(SVG[name], "image/svg+xml");\n    const icon = document.importNode(doc.documentElement, true);\n    const size = Number(options.size ?? 24);\n    if (!Number.isFinite(size) || size <= 0 || size > 512) throw new RangeError("Invalid icon size");\n    icon.setAttribute("width", String(size));\n    icon.setAttribute("height", String(size));\n    if (options.className) icon.setAttribute("class", "lucide " + String(options.className).replace(/[^a-zA-Z0-9_ -]/g, ""));\n    if (options.title) {\n      const title = document.createElementNS("http://www.w3.org/2000/svg", "title");\n      title.textContent = String(options.title);\n      icon.insertBefore(title, icon.firstChild);\n      icon.setAttribute("role", "img");\n      icon.setAttribute("aria-label", String(options.title));\n    } else {\n      icon.setAttribute("aria-hidden", "true");\n    }\n    return icon;\n  }\n  global.HFIcons = Object.freeze({ create, names: Object.freeze(Object.keys(SVG)) });\n})(window);\n`;
fs.writeFileSync(helper, helperText);
console.log(`Extracted ${names.length} icons from lucide-static@${pkg.version}`);
