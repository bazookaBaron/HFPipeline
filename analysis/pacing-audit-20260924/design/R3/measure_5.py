def med(x0,y0,x1,y1,sat=False,dark=None):
    r=im[y0:y1,x0:x1].reshape(-1,3)
    if sat: s=r.max(1)-r.min(1); r=r[s>=np.percentile(s,90)]
    if dark: L=r.sum(1); r=r[L<=np.percentile(L,dark)]
    return hx(np.median(r,0))
